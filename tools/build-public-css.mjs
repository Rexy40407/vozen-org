import fs from 'node:fs';
import path from 'node:path';
import { chromium } from '@playwright/test';
import puppeteer from 'puppeteer';
import { generate } from 'critical';

const checkOnly = process.argv.includes('--check');
const siteRoot = path.resolve('site');
const cssRoot = path.join(siteRoot, 'css');
const pages = {
  home: {
    html: path.join(siteRoot, 'index.html'),
    sources: ['main-v43.css', 'ecosystem-v1.css', 'global-nav-v1.css'],
  },
  tts: {
    html: path.join(siteRoot, 'tts', 'index.html'),
    sources: ['main-v43.css', 'ecosystem-bridge.css', 'global-nav-v1.css', 'tts-ui-v1.css'],
  },
  helper: {
    html: path.join(siteRoot, 'helper', 'index.html'),
    sources: ['main-v43.css', 'ecosystem-v1.css', 'global-nav-v1.css', 'helper-ui-preview.css'],
  },
};

const navCss = fs.readFileSync(path.join(cssRoot, 'global-nav-v1.css'), 'utf8');
const criticalFontCss = (navCss.match(/@font-face\s*\{[^}]*\}/g) || [])
  .join('\n');

const normalize = (value) => value.replace(/\r\n?/g, '\n');
const generatedHeader = (script) => `/* Generated by ${script}. Do not edit directly. */\n`;
const mismatches = [];

function compareOrWrite(output, expected) {
  let current = '';
  try { current = normalize(fs.readFileSync(output, 'utf8')); } catch {}
  if (current === expected) return;
  if (checkOnly) mismatches.push(path.relative(process.cwd(), output));
  else fs.writeFileSync(output, expected);
}

function createRenderDocument(html, css) {
  return normalize(html)
    .replace(/<link\b(?=[^>]*\brel=["']stylesheet["'])[^>]*>/gi, '')
    .replace(/<noscript>\s*<link\b[^>]*\brel=["']stylesheet["'][\s\S]*?<\/noscript>/gi, '')
    .replace('</head>', `<style data-critical-build>${css}</style></head>`);
}

const browser = await puppeteer.launch({
  executablePath: chromium.executablePath(),
  headless: true,
  args: ['--no-sandbox', '--disable-gpu', '--disable-dev-shm-usage'],
});

try {
  for (const [name, config] of Object.entries(pages)) {
    const fullBody = config.sources
      .map((sourceName) => `/* source: ${sourceName} */\n${normalize(fs.readFileSync(path.join(cssRoot, sourceName), 'utf8')).trim()}`)
      .join('\n\n');
    const fullCss = `${generatedHeader('tools/build-public-css.mjs')}${fullBody}\n`;
    compareOrWrite(path.join(cssRoot, `${name}-full-v1.css`), fullCss);

    const sourceHtml = fs.readFileSync(config.html, 'utf8');
    const result = await generate({
      html: createRenderDocument(sourceHtml, fullBody),
      base: siteRoot,
      dimensions: [
        { width: 320, height: 720 },
        { width: 375, height: 812 },
        { width: 768, height: 1024 },
        { width: 1440, height: 900 },
      ],
      concurrency: 1,
      inline: false,
      include: [
        /^\.nav(?:\b|__)/,
        /^\.brand(?:\b|__)/,
        /^\.lang(?:\b|__)/,
        /^\.vozen-global-nav/,
        /^\[data-vozen-nav\]/,
        /^\.btn(?:\b|--)/,
      ],
      rebase: false,
      ignore: { atrule: ['@font-face'] },
      cleanCSS: { level: { 1: { all: true }, 2: { all: false, removeDuplicateRules: true } } },
      penthouse: {
        blockJSRequests: true,
        renderWaitTime: 0,
        maxEmbeddedBase64Length: 24_000,
        puppeteer: { getBrowser: () => browser },
        unstableKeepBrowserAlive: true,
        unstableKeepOpenPages: 'all',
      },
    });
    const criticalCss = `${generatedHeader('tools/build-public-css.mjs')}${criticalFontCss}\n${result.css.trim()}\n`;
    compareOrWrite(path.join(cssRoot, `${name}-critical-v1.css`), criticalCss);
  }
} finally {
  await browser.close();
}

if (mismatches.length) {
  throw new Error(`public CSS bundles are stale; run npm run build:css\n${mismatches.join('\n')}`);
}
console.log(`[${checkOnly ? 'check' : 'build'}-public-css] ${Object.keys(pages).length} critical/full bundle pairs are current`);
