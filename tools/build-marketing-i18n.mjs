/* Generate the small public i18n overlay from the full workspace catalogue.
 *
 * Account, dashboard and payment strings stay in i18n-v42.js, which is loaded
 * only by private pages. Marketing keeps the public product/legal/nav strings
 * for all ten supported locales without downloading the private-workspace copy.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'site', 'js', 'i18n-v42.js');
const output = join(root, 'site', 'js', 'i18n-marketing-v1.js');
const checkOnly = process.argv.includes('--check');
const normalized = (value) => value.replace(/\r\n?/g, '\n');

const context = { window: { VOZEN_I18N: {}, dispatchEvent() {} } };
vm.createContext(context);
vm.runInContext(readFileSync(source, 'utf8'), context, { filename: source });

const isMarketingKey = (key) =>
  key.startsWith('ecosystem.') ||
  key.startsWith('home.') ||
  key.startsWith('tts.') ||
  key.startsWith('commands.') ||
  key.startsWith('legal.') ||
  key.startsWith('status.') ||
  key.startsWith('notFound.') ||
  key === 'hero.title1' ||
  key === 'hero.title2' ||
  /^feat\.(10|11|12)\./.test(key) ||
  key.startsWith('price.') ||
  key === 'site.status' ||
  key === 'site.github';

const overlay = Object.fromEntries(
  Object.entries(context.window.VOZEN_I18N).map(([locale, messages]) => [
    locale,
    Object.fromEntries(Object.entries(messages).filter(([key]) => isMarketingKey(key))),
  ]),
);
const generated =
  '/* Generated by tools/build-marketing-i18n.mjs from i18n-v42.js. */\n' +
  '(function () {\n' +
  '  "use strict";\n' +
  `  var overlay = ${JSON.stringify(overlay)};\n` +
  '  var dictionary = window.VOZEN_I18N || {};\n' +
  '  Object.keys(overlay).forEach(function (locale) {\n' +
  '    dictionary[locale] = Object.assign({}, dictionary[locale] || {}, overlay[locale]);\n' +
  '  });\n' +
  '  window.VOZEN_I18N = dictionary;\n' +
  '  try { window.dispatchEvent(new CustomEvent("vozen:i18nready")); } catch (_) {}\n' +
  '}());\n';

if (checkOnly) {
  let current = '';
  try { current = readFileSync(output, 'utf8'); } catch {}
  if (normalized(current) !== normalized(generated)) {
    throw new Error('site/js/i18n-marketing-v1.js is out of date; run npm run build:i18n:marketing');
  }
  console.log(`[check-marketing-i18n] ${Object.keys(overlay).length} languages · public overlay is current`);
} else {
  writeFileSync(output, generated);
  console.log(`[build-marketing-i18n] ${Object.keys(overlay).length} languages · ${output}`);
}
