/* Build one deliberately small public catalogue per locale.
 *
 * The JSON files in tools/i18n-marketing-src are the public source of truth.
 * `--extract-legacy` is a one-time migration helper for the former monolithic
 * catalogues; ordinary builds never read those runtime files.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDirectory = join(root, 'tools', 'i18n-marketing-src');
const outputDirectory = join(root, 'site', 'js', 'i18n-public');
const locales = ['en', 'pt', 'fr', 'es', 'de', 'tr', 'ar', 'zh', 'ru', 'ko'];
const checkOnly = process.argv.includes('--check');
const extractLegacy = process.argv.includes('--extract-legacy');
const normalized = (value) => value.replace(/\r\n?/g, '\n');
const excludedPrefixes = ['account.', 'billing.', 'dashboard.', 'panel.', 'claim.'];
const publicPrefixes = [
  'ecosystem.', 'home.', 'tts.', 'commands.', 'legal.', 'status.', 'notFound.',
  'hero.', 'feat.', 'price.', 'nav.', 'common.', 'cta.', 'hear.', 'stat.',
  'lang.', 'games.', 'setup.', 'cmd.', 'faq.', 'finale.', 'foot.', 'premium.',
  'helper.landing.', 'helper.module',
];

const isPublicKey = (key) =>
  !excludedPrefixes.some((prefix) => key.startsWith(prefix)) &&
  (publicPrefixes.some((prefix) => key.startsWith(prefix)) || key.startsWith('site.'));

function legacyCatalogue() {
  const context = { window: { VOZEN_I18N: {}, dispatchEvent() {} } };
  vm.createContext(context);
  for (const filename of ['i18n-v41.js', 'i18n-v42.js']) {
    const source = join(root, 'site', 'js', filename);
    vm.runInContext(readFileSync(source, 'utf8'), context, { filename: source });
  }
  return context.window;
}

function extractLegacySources() {
  const catalogue = legacyCatalogue();
  mkdirSync(sourceDirectory, { recursive: true });
  for (const locale of locales) {
    const messages = Object.fromEntries(
      Object.entries(catalogue.VOZEN_I18N[locale] || {}).filter(([key]) => isPublicKey(key)),
    );
    const commands = Object.fromEntries(
      Object.entries(catalogue.VOZEN_COMMANDS || {}).map(([category, rows]) => [
        category,
        rows.map(([name, descriptions]) => [name, descriptions[locale] || descriptions.en || '']),
      ]),
    );
    const faq = (catalogue.VOZEN_FAQ || []).map(([question, answer]) => [
      question[locale] || question.en || '',
      answer[locale] || answer.en || '',
    ]);
    writeFileSync(
      join(sourceDirectory, `${locale}.json`),
      `${JSON.stringify({ locale, messages, commands, faq }, null, 2)}\n`,
    );
  }
  console.log(`[extract-marketing-i18n] wrote ${locales.length} structured locale sources`);
}

function generatedBundle(source) {
  return `/* Generated by tools/build-marketing-i18n.mjs from tools/i18n-marketing-src/${source.locale}.json. */\n` +
    '(function () {\n' +
    '  "use strict";\n' +
    `  var locale = ${JSON.stringify(source.locale)};\n` +
    `  var messages = ${JSON.stringify(source.messages)};\n` +
    `  var incomingCommands = ${JSON.stringify(source.commands)};\n` +
    `  var incomingFaq = ${JSON.stringify(source.faq)};\n` +
    '  var dictionary = window.VOZEN_I18N || {};\n' +
    '  dictionary[locale] = Object.assign({}, dictionary[locale] || {}, messages);\n' +
    '  window.VOZEN_I18N = dictionary;\n' +
    '  var commands = window.VOZEN_COMMANDS || {};\n' +
    '  Object.keys(incomingCommands).forEach(function (category) {\n' +
    '    commands[category] = commands[category] || [];\n' +
    '    incomingCommands[category].forEach(function (row, index) {\n' +
    '      var target = commands[category][index];\n' +
    '      if (!target || target[0] !== row[0]) target = commands[category][index] = [row[0], {}];\n' +
    '      target[1][locale] = row[1];\n' +
    '    });\n' +
    '  });\n' +
    '  window.VOZEN_COMMANDS = commands;\n' +
    '  var faq = window.VOZEN_FAQ || [];\n' +
    '  incomingFaq.forEach(function (row, index) {\n' +
    '    var target = faq[index] || (faq[index] = [{}, {}]);\n' +
    '    target[0][locale] = row[0];\n' +
    '    target[1][locale] = row[1];\n' +
    '  });\n' +
    '  window.VOZEN_FAQ = faq;\n' +
    '  try { window.dispatchEvent(new CustomEvent("vozen:i18nready", { detail: { language: locale } })); } catch (_) {}\n' +
    '}());\n';
}

if (extractLegacy) extractLegacySources();

mkdirSync(outputDirectory, { recursive: true });
const availableSources = new Set(readdirSync(sourceDirectory).filter((name) => name.endsWith('.json')));
for (const locale of locales) {
  const filename = `${locale}.json`;
  if (!availableSources.has(filename)) throw new Error(`missing structured public source: ${filename}`);
  const source = JSON.parse(readFileSync(join(sourceDirectory, filename), 'utf8'));
  if (source.locale !== locale) throw new Error(`${filename} declares locale ${source.locale}`);
  const generated = generatedBundle(source);
  const output = join(outputDirectory, `${locale}.js`);
  if (checkOnly) {
    let current = '';
    try { current = readFileSync(output, 'utf8'); } catch {}
    if (normalized(current) !== normalized(generated)) {
      throw new Error(`site/js/i18n-public/${locale}.js is out of date; run npm run build:i18n:marketing`);
    }
  } else {
    writeFileSync(output, generated);
  }
}

console.log(`[${checkOnly ? 'check' : 'build'}-marketing-i18n] ${locales.length} isolated locale bundles are current`);
